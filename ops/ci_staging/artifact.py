"""Bounded, deterministic static artifacts for the separate CI staging identity."""
import io
import json
from pathlib import Path
import stat
import zipfile
from html.parser import HTMLParser
from .trust import ORIGIN, BRANCH, HERO_ORIGIN, WORKFLOW_ID, MAX_TOTAL, MAX_ZIP, require, valid_sha, safe_name, digest


class Page(HTMLParser):
    def __init__(self):
        super().__init__(); self.robots=[]; self.canonicals=[]; self.links=[]
    def handle_starttag(self,tag,attrs):
        a=dict(attrs)
        if tag=='meta' and a.get('name')=='robots':self.robots.append(a.get('content'))
        if tag=='link' and a.get('rel')=='canonical':self.canonicals.append(a.get('href'))
        if tag=='a':self.links.append(a.get('href',''))


def encode(value):
    return (json.dumps(value,sort_keys=True,separators=(',',':'))+'\n').encode()


def sequence(run):
    require(type(run['run_number']) is int and run['run_number']>0 and type(run['run_attempt']) is int and 0<run['run_attempt']<100000, 'Invalid CI sequence')
    return run['run_number']*100000+run['run_attempt']


def zip_bytes(files):
    out=io.BytesIO()
    with zipfile.ZipFile(out,'w',compression=zipfile.ZIP_STORED) as z:
        for name,data in sorted(files.items()):
            require(safe_name(name), 'Unsafe archive path')
            entry=zipfile.ZipInfo(name,(1980,1,1,0,0,0));entry.create_system=3;entry.external_attr=(stat.S_IFREG|0o644)<<16
            z.writestr(entry,data)
    require(out.tell()<=MAX_ZIP, 'Archive exceeds limit')
    return out.getvalue()


def read_zip(data, expected=None, total_limit=MAX_TOTAL):
    require(len(data)<=MAX_ZIP+2*1024*1024, 'ZIP exceeds limit')
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        entries=z.infolist();names=[e.filename for e in entries]
        require(len(entries)<5000 and len(set(names))==len(names), 'Duplicate/excessive ZIP inventory')
        require(sum(e.file_size for e in entries)<=total_limit, 'Expanded archive exceeds limit')
        if expected is not None: require(set(names)==set(expected), 'Unexpected ZIP inventory')
        result={}
        for e in entries:
            require(safe_name(e.filename) and not e.is_dir() and not e.flag_bits & 1 and stat.S_IFMT(e.external_attr>>16) in (0,stat.S_IFREG), 'Unsafe ZIP path/type/encryption')
            result[e.filename]=z.read(e)
        return result


def payload(directory, sha, run, policy, note=None):
    require(valid_sha(sha), 'Invalid source SHA')
    files={}
    for p in Path(directory).rglob('*'):
        require(not p.is_symlink(), 'Linked artifact input')
        if p.is_dir():continue
        require(p.is_file(), 'Special artifact input')
        files[p.relative_to(directory).as_posix()]=p.read_bytes()
    require('staging-revision.json' not in files, 'Revision must be generated by trusted packager')
    revision={'source_sha':sha,'hero_origin':HERO_ORIGIN}
    if note is not None:
        require(type(note) is dict and set(note)=={'note'} and isinstance(note['note'],str) and len(note['note'])<=120, 'Invalid staging-only verification note')
        revision['note']=note['note']
    files['staging-revision.json']=encode(revision)
    archive=zip_bytes(files)
    m={'schema':'ci-staging/v1','authority':'github-actions-staging','site':ORIGIN,'branch':BRANCH,'source_sha':sha,'workflow_id':WORKFLOW_ID,'run_id':run['id'],'run_number':run['run_number'],'run_attempt':run['run_attempt'],'sequence':sequence(run),'robots':'noindex, nofollow','purchasing_enabled':False,'commerce_destinations':{},'archive_sha256':digest(archive),'original_media':policy['original_media'],'files':[{'path':n,'bytes':len(d),'sha256':digest(d)} for n,d in sorted(files.items())]}
    validate(m,archive,policy,sha,run)
    return m,archive


def validate(m,archive,policy,sha,run):
    require(m.get('schema')=='ci-staging/v1' and m.get('authority')=='github-actions-staging', 'Not a CI staging release')
    require(m.get('site')==ORIGIN and m.get('branch')==BRANCH and m.get('source_sha')==sha and valid_sha(sha), 'Release source/target mismatch')
    require(m.get('workflow_id')==WORKFLOW_ID and all(m.get(k)==run[v] for k,v in [('run_id','id'),('run_number','run_number'),('run_attempt','run_attempt')]) and m.get('sequence')==sequence(run), 'Release run/attempt mismatch')
    require(m.get('robots')=='noindex, nofollow' and m.get('purchasing_enabled') is False and m.get('commerce_destinations')=={}, 'Unsafe staging metadata/commerce')
    require(m.get('original_media')==policy['original_media'], 'Original media dimensions/provenance mismatch')
    require(len(archive)<=MAX_ZIP and digest(archive)==m.get('archive_sha256'), 'Archive hash/limit mismatch')
    records=m['files']; inventory={f['path']:f for f in records}
    require(len(inventory)==len(records) and bool(records), 'Duplicate/empty manifest inventory')
    files=read_zip(archive,inventory)
    require(sum(len(d) for d in files.values())<=MAX_TOTAL, 'Expanded release exceeds limit')
    for name,data in files.items():
        f=inventory[name]
        require(type(f['bytes']) is int and f['bytes']==len(data) and f['sha256']==digest(data), 'Per-file digest mismatch')
        if name in policy['public_files']:
            require(policy['public_files'][name]=={'sha256':digest(data),'bytes':len(data)}, 'Pinned public/media bytes changed')
        elif name=='staging-revision.json':
            revision=json.loads(data)
            require(revision.get('source_sha')==sha and revision.get('hero_origin')==HERO_ORIGIN and set(revision)<= {'source_sha','hero_origin','note'}, 'Invalid public revision')
        elif name.endswith('.html'):
            import re
            require(name=='index.html' or re.fullmatch(r'(en|ml|hi|ta)/(?:[a-z0-9-]+/)*index\.html',name), 'Unsafe HTML route')
            page=Page();page.feed(data.decode('utf-8'))
            require(page.robots==['noindex, nofollow'] and page.canonicals==[ORIGIN+'/'+name.removesuffix('index.html')], 'Unsafe page metadata')
            require(not any('mariyasnaturals.com' in href for href in page.links), 'Purchasing link is forbidden')
        elif name=='robots.txt':require(data==b'User-agent: *\nDisallow: /\n', 'Unsafe robots policy')
        elif name in ('sitemap-index.xml','sitemap-0.xml'):require(ORIGIN.encode() in data and b'mariyasnaturals.in' not in data, 'Wrong sitemap origin')
        else:
            import re
            require(re.fullmatch(r'_astro/[A-Za-z0-9_.-]+\.(css|js)',name), 'Unexpected release file')
    require(set(policy['public_files'])<=set(files), 'Missing original/public media')
    require({'index.html','en/index.html','ml/index.html','hi/index.html','ta/index.html','robots.txt','staging-revision.json'}<=set(files), 'Missing language/revision output')
    return files
