import { readFile, writeFile, mkdir, copyFile, stat } from 'node:fs/promises';
import { resolve } from 'node:path';
import { format } from 'prettier';
const root = resolve(import.meta.dirname, '..');
const selections = [
  ['inter', 'latin', 'wght'],
  ['cormorant-garamond', 'latin', 'wght'],
  ['noto-sans-malayalam', 'malayalam', 'wght'],
  ['noto-serif-malayalam', 'malayalam', 'wght'],
  ['noto-sans-devanagari', 'devanagari', 'wght'],
  ['noto-serif-devanagari', 'devanagari', 'wght'],
  ['noto-sans-tamil', 'tamil', 'wght'],
  ['noto-serif-tamil', 'tamil', 'wght'],
];
await mkdir(resolve(root, 'public/fonts/licenses'), { recursive: true });
let css =
  '/* Generated by npm run fonts:prepare. OFL-1.1 licenses: /fonts/licenses/. */\n';
const manifest = [];
for (const [name, subset, axis] of selections) {
  const directory = resolve(root, `node_modules/@fontsource-variable/${name}`);
  const source = await readFile(resolve(directory, `${axis}.css`), 'utf8');
  const face = source.match(
    new RegExp(
      `@font-face \\{[^}]*${name}-${subset}-${axis}-normal\\.woff2[^}]*\\}`,
      's',
    ),
  )?.[0];
  if (!face) throw new Error(`Missing font subset ${name}/${subset}`);
  const filename = `${name}-${subset}-${axis}-normal.woff2`;
  await copyFile(
    resolve(directory, 'files', filename),
    resolve(root, 'public/fonts', filename),
  );
  await copyFile(
    resolve(directory, 'LICENSE'),
    resolve(root, 'public/fonts/licenses', `${name}.txt`),
  );
  css += face.replace(`./files/${filename}`, `/fonts/${filename}`) + '\n';
  manifest.push({
    name,
    subset,
    path: `/fonts/${filename}`,
    bytes: (await stat(resolve(directory, 'files', filename))).size,
    license: `/fonts/licenses/${name}.txt`,
  });
}
await writeFile(
  resolve(root, 'src/styles/fonts.css'),
  await format(css, { parser: 'css', singleQuote: true }),
);
await writeFile(
  resolve(root, 'src/data/font-manifest.json'),
  await format(JSON.stringify(manifest), { parser: 'json' }),
);
console.log(
  `Prepared ${manifest.length} WOFF2 subsets, ${manifest.reduce((n, f) => n + f.bytes, 0)} bytes across all languages.`,
);
