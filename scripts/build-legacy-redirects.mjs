#!/usr/bin/env node
/**
 * Generates the *proposed* legacy-to-new redirect map for mariyasnaturals.in.
 *
 * The old WordPress/WooCommerce site used the same product slugs the live store
 * still uses, so a legacy `/product/<slug>/` can be resolved to a catalogue
 * record by slug and then to the static route by SKU. Nothing here is enabled:
 * the output is a draft for the NGINX snippet in `release/nginx/`, to be checked
 * against the real URL inventory before it is pasted anywhere.
 *
 * Rules, in order:
 *   1. visible product   -> the static page on .in (it is the discovery page now)
 *   2. hidden product    -> the official .com product URL (the store survives)
 *   3. withdrawn product -> 410 Gone (never resurrect the 1-litre pack)
 *   4. category archive  -> the matching .in collection
 *   5. commerce paths    -> the same path on .com (cart, checkout, account …)
 *   6. WordPress paths   -> 410 Gone (they can never come back on a static host)
 *
 * Usage: node scripts/build-legacy-redirects.mjs [outfile]
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const outfile =
  process.argv[2] || join(root, 'release/nginx/legacy-redirects.proposed.conf');

const catalogue = JSON.parse(
  readFileSync(join(root, 'catalogue/catalogue-source.json'), 'utf8'),
);
const visibility = JSON.parse(
  readFileSync(join(root, 'src/data/product-visibility.json'), 'utf8'),
);
const hiddenIds = new Set(
  (visibility.hidden ?? []).map((entry) => entry.storeProductId),
);
/*
 * Withdrawn listings are recorded by store id only — the catalogue snapshot keeps
 * no record for them, so their legacy slug is unknown. They are reported, never
 * guessed: inventing a URL to redirect would be worse than leaving it to the 404.
 */
const withdrawn = catalogue.exclusions ?? [];
/** Static product routes, keyed by the SKU the catalogue records for them. */
if (!existsSync(join(root, 'dist/en/products'))) {
  console.error(
    'dist/en/products is missing — build the site first, or every visible product ' +
      'would be mapped to the store instead of its static page.',
  );
  process.exit(1);
}
const routesBySku = new Map();
for (const dir of readdirSync(join(root, 'dist/en/products'))) {
  if (dir === 'index.html' || dir.includes('.')) continue;
  const sku = dir.match(/-(\d+)$/)?.[1];
  if (sku) routesBySku.set(sku, `/en/products/${dir}/`);
}

const products = [];
const categories = [];
for (const record of catalogue.records) {
  const legacy = `/product/${record.slug}/`;
  const route = record.sku ? routesBySku.get(String(record.sku)) : undefined;
  if (hiddenIds.has(record.id) || !route) {
    products.push([legacy, record.url]);
  } else {
    products.push([legacy, route]);
  }
  for (const category of record.categories ?? []) {
    const slug = String(category.slug ?? '').toLowerCase();
    if (slug) categories.push([`/product-category/${slug}/`, slug]);
  }
}

const COLLECTION_SLUGS = {
  'hair-care': '/en/collections/hair-care/',
  'baby-care': '/en/collections/baby-care/',
  'skin-care': '/en/collections/skin-care/',
  'herbal-powders': '/en/collections/herbal-powders/',
  wellness: '/en/collections/wellness/',
  accessories: '/en/products/',
};
const categoryMap = new Map();
for (const [legacy, slug] of categories) {
  const target =
    COLLECTION_SLUGS[slug] ?? `https://www.mariyasnaturals.com${legacy}`;
  categoryMap.set(legacy, target);
}
for (const [slug, target] of Object.entries(COLLECTION_SLUGS))
  if (!categoryMap.has(`/product-category/${slug}/`))
    categoryMap.set(`/product-category/${slug}/`, target);

const COMMERCE = {
  '/cart/': 'https://www.mariyasnaturals.com/cart/',
  '/checkout/': 'https://www.mariyasnaturals.com/checkout/',
  '/my-account/': 'https://www.mariyasnaturals.com/my-account/',
  '/shop/': 'https://www.mariyasnaturals.com/shop/',
  '/wishlist/': 'https://www.mariyasnaturals.com/wishlist/',
  '/compare/': 'https://www.mariyasnaturals.com/compare/',
};

const lines = [];
lines.push(
  '# PROPOSED — not enabled anywhere. Review against the real URL inventory',
);
lines.push(
  '# (Search Console → Pages, the host access log, or /wp-sitemap.xml while the',
);
lines.push(
  '# WordPress site still answers) before pasting this into a server block.',
);
lines.push('# Generated by scripts/build-legacy-redirects.mjs from');
lines.push(
  '# catalogue/catalogue-source.json + src/data/product-visibility.json.',
);
lines.push('');
lines.push(
  '# Usage inside the apex :443 server block, after the static root is set:',
);
lines.push('#   map $uri $legacy_target {');
lines.push('#       ...this map...');
lines.push('#       default "";');
lines.push('#   }');
lines.push('#   if ($legacy_target = gone) { return 410; }');
lines.push('#   if ($legacy_target != "")  { return 301 $legacy_target; }');
lines.push('');
lines.push('map $uri $legacy_target {');
lines.push('    default "";');
lines.push('');
lines.push(
  '    # Products — the 59 visible pages move to the discovery site, the 26',
);
lines.push(
  '    # hidden listings and every other record go to the store that still sells them.',
);
for (const [legacy, target] of products.sort((a, b) =>
  a[0].localeCompare(b[0]),
))
  lines.push(`    ${legacy.padEnd(52)} ${target};`);
lines.push('');
lines.push('    # Category archives.');
for (const [legacy, target] of [...categoryMap].sort((a, b) =>
  a[0].localeCompare(b[0]),
))
  lines.push(`    ${legacy.padEnd(52)} ${target};`);
lines.push('');
lines.push('    # Commerce stays commerce: these paths belong to the store.');
for (const [legacy, target] of Object.entries(COMMERCE))
  lines.push(`    ${legacy.padEnd(52)} ${target};`);
lines.push('');
if (withdrawn.length) {
  lines.push(
    '    # Withdrawn listings (410 Gone once their legacy slug is known):',
  );
  for (const entry of withdrawn)
    lines.push(
      `    #   store id ${entry.id} — ${String(entry.reason).split('.')[0]}.`,
    );
  lines.push('');
}
lines.push('    # WordPress artefacts can never come back on a static host.');
for (const legacy of [
  '/wp-login.php',
  '/wp-admin/',
  '/wp-json/',
  '/feed/',
  '/?s=',
  '/xmlrpc.php',
])
  lines.push(`    ${legacy.padEnd(52)} gone;`);
lines.push('}');
lines.push('');

writeFileSync(outfile, lines.join('\n'));
console.log(
  `wrote ${outfile}: ${products.length} product rules, ${categoryMap.size} category rules, ${Object.keys(COMMERCE).length} commerce rules, ${withdrawn.length} withdrawn listing(s) reported for manual mapping`,
);
